#!/usr/bin/env bash
# build.sh - fetch and build the pdfium benchmark binaries, BOLT-ready.
#
#   * clones pdfium (GitHub mirror, pinned to branch chromium/7533) into
#     work/pdfium
#   * clones the minimal DEPS set (build/, buildtools/, partition_allocator,
#     abseil-cpp, fast_float, freetype2, libjpeg_turbo, libpng, zlib, icu,
#     nasm, test_fonts) at the revisions pinned in the checkout's DEPS -
#     plain git, no depot_tools; skia/v8/gtest/corpus are NOT needed
#     (verified by grepping the build graph)
#   * downloads the gn binary from CIPD (version from DEPS) into
#     intermediates/tools/
#   * builds libpdfium.a with GN/ninja and the BOLT flags (extra_cflags /
#     extra_ldflags), then links the harness pdfium_bench and the input
#     generator gen_pdf against it
#
# Like every other app in the testbed, the toolchain is taken from PATH
# (clang++ / ld.lld / llvm-objcopy) or set LLVM_BIN explicitly.
# pdfium's GN build additionally needs the toolchain root as
# clang_base_path, which is derived from the same directory.
# CFLAGS_BOLT / LDFLAGS_BOLT can be overridden via the environment.
#
# Notes / gotchas (documented in README.md):
#   * clang_version is derived from the deploy tree (lib/clang/*); this
#     build revision's default of "22" would be wrong for clang-24
#   * the deploy LLVM lacks compiler-rt builtins; the system compiler-rt
#     archive is copied into the deploy tree (needed only for the nasm host
#     tool)
#   * use_sysroot=false (system glibc) also turns off clang modules, which
#     avoids the third_party/libc++ sources entirely
#   * clang_use_chrome_plugins=false (deploy has no chrome clang plugins)
#   * chromium's build adds -Wa,--crel; llvm-bolt 24 handles CREL
#     relocations fine (verified)
#
# Usage: build.sh

set -e

source "$(cd "$(dirname "$0")/.." && pwd)/vars.sh"

# default the toolchain to the clang++ on PATH (testbed convention); the
# GN build needs clang_base_path, so the toolchain root is derived from it
LLVM_BIN="${LLVM_BIN:-}"
if [ -z "$LLVM_BIN" ]; then
  CXX=$(command -v clang++ 2>/dev/null || true)
  LLVM_BIN=${CXX:+$(dirname "$CXX")}
fi
CLANG_BASE="${CLANG_BASE:-$(dirname "$LLVM_BIN")}"
# the clang major version living in the toolchain (drives both the GN
# clang_version arg and the compiler-rt builtins path):
CLANG_VER=$(ls "$CLANG_BASE/lib/clang" 2>/dev/null | head -1)
BUILTINS_SRC="${BUILTINS_SRC:-/usr/lib/clang/21/lib/linux/libclang_rt.builtins-x86_64.a}"

require "$LLVM_BIN/clang++" "clang++ not found (set LLVM_BIN or put a clang toolchain on PATH)"
require "$LLVM_BIN/ld.lld" "ld.lld not found next to clang++ (set LLVM_BIN)"

# --- fetch the source (idempotent) ------------------------------------------
# pinned source: GitHub mirror branch chromium/7533 (Chromium branch position,
# ~2024; there are no release tags). To update, change the pin and re-clone
# (rm -rf work/pdfium):
fetch_repo https://github.com/chromium/pdfium.git chromium/7533

# --- fetch the minimal DEPS set at the pinned revisions (plain git) --------
fetch_dep() {  # fetch_dep <dest> <url> <sha>
  local dest=$1 url=$2 sha=$3
  if [ -d "$SRC_DIR/$dest/.git" ]; then return 0; fi
  echo "== fetching $dest @ $sha ..."
  mkdir -p "$SRC_DIR/$dest"
  ( cd "$SRC_DIR/$dest"
    git init -q
    git remote add origin "$url"
    git fetch -q --depth 1 origin "$sha"
    git checkout -q FETCH_HEAD )
}

rev() { grep -oE "'$1': '[0-9a-f]+'" "$SRC_DIR/DEPS" | grep -oE "[0-9a-f]{40}" | head -1; }

CG=https://chromium.googlesource.com
fetch_dep build "$CG/chromium/src/build.git" "$(rev build_revision)"
fetch_dep buildtools "$CG/chromium/src/buildtools.git" "$(rev buildtools_revision)"
fetch_dep base/allocator/partition_allocator "$CG/chromium/src/base/allocator/partition_allocator.git" "$(rev partition_allocator_revision)"
fetch_dep third_party/abseil-cpp "$CG/chromium/src/third_party/abseil-cpp.git" "$(rev abseil_revision)"
fetch_dep third_party/fast_float/src "$CG/external/github.com/fastfloat/fast_float.git" "$(rev fast_float_revision)"
fetch_dep third_party/freetype/src "$CG/chromium/src/third_party/freetype2.git" "$(rev freetype_revision)"
fetch_dep third_party/libjpeg_turbo "$CG/chromium/deps/libjpeg_turbo.git" "$(rev jpeg_turbo_revision)"
fetch_dep third_party/libpng "$CG/chromium/src/third_party/libpng.git" "$(rev libpng_revision)"
fetch_dep third_party/zlib "$CG/chromium/src/third_party/zlib.git" "$(rev zlib_revision)"
fetch_dep third_party/icu "$CG/chromium/deps/icu.git" "$(rev icu_revision)"
fetch_dep third_party/nasm "$CG/chromium/deps/nasm.git" "$(rev nasm_source_revision)"
fetch_dep third_party/test_fonts "$CG/chromium/src/third_party/test_fonts.git" "$(rev test_fonts_revision)"

# gclient_args.gni is normally generated by gclient; an empty one suffices
# (its args are only read when present).
mkdir -p "$SRC_DIR/build/config"
[ -f "$SRC_DIR/build/config/gclient_args.gni" ] || : > "$SRC_DIR/build/config/gclient_args.gni"

# --- gn (CIPD, version from DEPS) -------------------------------------------
GN_VERSION=$(grep -oE "'gn_version': 'git_revision:[0-9a-f]+'" "$SRC_DIR/DEPS" | grep -oE "[0-9a-f]{40}")
GN=$TOOLS_INT/gn
if [ ! -x "$GN" ]; then
  echo "== downloading gn @ $GN_VERSION ..."
  curl -sL "https://chrome-infra-packages.appspot.com/dl/gn/gn/linux-amd64/+/git_revision:$GN_VERSION" -o /tmp/gn.zip
  mkdir -p "$TOOLS_INT"
  unzip -oq /tmp/gn.zip -d "$TOOLS_INT"
fi

# --- compiler-rt builtins for the nasm host tool ----------------------------
# chromium links host tools with -rtlib=compiler-rt; the deploy LLVM ships no
# builtins, so use the system compiler-rt archive (ABI-stable freestanding
# helpers, only affects the nasm assembler host tool):
BUILTINS_DST="$CLANG_BASE/lib/clang/$CLANG_VER/lib/x86_64-unknown-linux-gnu/libclang_rt.builtins.a"
if [ ! -f "$BUILTINS_DST" ]; then
  echo "== copying system compiler-rt builtins into the deploy tree ..."
  require "$BUILTINS_SRC" "no system libclang_rt.builtins at $BUILTINS_SRC (set BUILTINS_SRC)"
  mkdir -p "$(dirname "$BUILTINS_DST")"
  cp "$BUILTINS_SRC" "$BUILTINS_DST"
fi

# --- configure + build libpdfium.a ------------------------------------------
# gn_list "a b c" -> ["a","b","c"] (GN string array); the BOLT flags come
# from the shared CFLAGS_BOLT / LDFLAGS_BOLT (vars.sh, env-overridable), so
# overrides reach libpdfium.a as well as the harnesses.
gn_list() {
  local out=""
  for f in $1; do out="$out\"$f\","; done
  printf '[%s]' "${out%,}"
}
GN_CFLAGS=$(gn_list "$CFLAGS_BOLT")
GN_LDFLAGS=$(gn_list "$LDFLAGS_BOLT")

if [ ! -f "$BUILD_DIR/obj/libpdfium.a" ]; then
  echo "== gn gen ..."
  "$GN" gen "$BUILD_DIR" --args="
is_debug=false
is_component_build=false
pdf_is_complete_lib=true
pdf_enable_v8=false
pdf_enable_xfa=false
treat_warnings_as_errors=false
use_custom_libcxx=false
symbol_level=1
enable_nacl=false
use_sysroot=false
clang_version=\"$CLANG_VER\"
clang_use_chrome_plugins=false
clang_base_path=\"$CLANG_BASE\"
extra_cflags=$GN_CFLAGS
extra_ldflags=$GN_LDFLAGS
"
  echo "== ninja pdfium ..."
  ninja -C "$BUILD_DIR" pdfium
fi

# --- build harness + generator ----------------------------------------------
# CFLAGS_BOLT / LDFLAGS_BOLT come from vars.sh (env-overridable), the same
# flags that went into libpdfium.a above.
echo "== building pdfium_bench + gen_pdf ..."
mkdir -p "$INT_DIR"
for t in pdfium_bench gen_pdf; do
  if [ ! -x "$INT_DIR/$t" ]; then
    "$LLVM_BIN/clang++" $CFLAGS_BOLT -std=c++17 -I "$SRC_DIR/public" \
      "$SCRIPT_DIR/$t.cpp" "$BUILD_DIR/obj/libpdfium.a" $LDFLAGS_BOLT \
      -lpthread -o "$INT_DIR/$t"
    # the .sframe gotcha (see README): strip it before profiling/use
    OBJCOPY="$LLVM_BIN/llvm-objcopy"
    command -v "$OBJCOPY" > /dev/null 2>&1 || OBJCOPY=$(command -v llvm-objcopy || command -v objcopy)
    "$OBJCOPY" --remove-section=.sframe --remove-section=.rela.sframe "$INT_DIR/$t"
  fi
done

echo "pdfium ready: $INT_DIR/pdfium_bench, $INT_DIR/gen_pdf"
